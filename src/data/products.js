/**
 * Find a product by its ID
 */
export function getProductById(id) {
  if (!id) return undefined;
  return coffeeProducts.find(
    (product) => product.id.toLowerCase() === id.toLowerCase()
  );
}

/**
 * Filter products by search term (case-insensitive, partial matching)
 */
export function searchProducts(query) {
  if (!query || typeof query !== "string") return [];
  const term = query.trim().toLowerCase();
  if (!term) return [];

  return coffeeProducts.filter((product) => {
    const matchName = product.name.toLowerCase().includes(term);
    const matchCategory = product.category.toLowerCase().includes(term);
    const matchOrigin = product.origin.toLowerCase().includes(term);
    const matchRoast = product.roast.toLowerCase().includes(term);
    const matchNotes = product.notes.some((n) => n.toLowerCase().includes(term));
    const matchDescription = product.description.toLowerCase().includes(term);

    return (
      matchName ||
      matchCategory ||
      matchOrigin ||
      matchRoast ||
      matchNotes ||
      matchDescription
    );
  });
}
